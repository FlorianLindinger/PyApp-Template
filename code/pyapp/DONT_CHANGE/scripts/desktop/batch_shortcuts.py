"""Optional movable command-line entry points matching Setup's enabled shortcuts."""

from __future__ import annotations

from pathlib import Path
from types import ModuleType, SimpleNamespace
from typing import List, Union

from pyapp.DONT_CHANGE.scripts.desktop.shortcuts import shortcut_definitions, shortcut_filename

SIGNATURE = "rem Generated by PyApp Setup: batch argument launcher."


def sync(s: Union[ModuleType, SimpleNamespace], app_id: str, root: Path) -> List[Path]:
    """Write enabled entry points; remove only our own stale files, never unrelated files."""
    folder = root / "batch_shortcuts"
    if folder.is_symlink() or folder.resolve().parent != root.resolve():
        raise OSError("Batch shortcut folder resolves outside the project root.")
    wanted = {}
    if s.generate_batch_shortcuts_for_args_launch:
        for kind, name, _icon, _launcher, _args, _identity, _description in shortcut_definitions(s, app_id):
            filename = Path(shortcut_filename(name)).with_suffix(".cmd").name
            header = "@echo off\n" + SIGNATURE + "\nsetlocal EnableExtensions DisableDelayedExpansion\n"
            if kind in ("terminal", "no_terminal", "browser_terminal"):
                mode = "browser" if kind == "browser_terminal" else kind
                # No CALL around user arguments: CALL parses percent/metacharacters twice.
                text = (
                    header
                    + 'if not defined PYAPP_START_DIR set "PYAPP_START_DIR=%CD%"\n'
                    + f'set "PYAPP_LAUNCH_MODE={mode}"\nset "PYAPP_BATCH_ARGUMENTS=1"\n'
                    # B\A.bat is the only launcher path named here (it keeps its place between
                    # versions); it sets PYAPP_PYTHON, PYAPP_ENTRYPOINT and PYAPP_START_PROGRAM.
                    + 'call "%~dp0..\\code\\pyapp\\DONT_CHANGE\\B\\A.bat"\n'
                    + "if errorlevel 1 exit /b 1\n"
                    + f'"%PYAPP_PYTHON%" -I -S -X utf8 "%PYAPP_ENTRYPOINT%" "%PYAPP_START_PROGRAM%" "{app_id}" %*\n'
                    + "exit /b %ERRORLEVEL%\n"
                )
            else:
                # Derive the Unicode shortcut name from this batch's filename rather than
                # embedding UTF-8 text that cmd.exe might decode using another code page.
                text = header + 'start "" "%~dp0..\\%~n0.lnk"\n'
            wanted[folder / filename] = text
    for path, text in wanted.items():
        if path.exists() and SIGNATURE not in path.read_text(encoding="utf-8"):
            raise FileExistsError(f"Refusing to overwrite an unrelated batch file: {path}")
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="") as stream:
            stream.write(text.replace("\n", "\r\n"))
    if folder.is_dir():
        for path in folder.glob("*.cmd"):
            if path not in wanted and SIGNATURE in path.read_text(encoding="utf-8"):
                path.unlink()
    return list(wanted)
